/* eslint-disable @typescript-eslint/no-require-imports -- standalone Node test */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const model = {};
new Function('exports', ts.transpileModule(fs.readFileSync('app/_model/section-questions.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)(model);
const {sectionAt,enrichQuestion,clusterSectionQuestions,classifyQuestionRule} = model;
const s = (id,x,y,width,height,pageId='p') => ({id,pageId,x,y,width,height,title:id,text:'',type:'mixed',source:'semantic',embedding:null});
const sections = [s('big',.1,.1,.6,.6),s('small',.2,.2,.1,.1),s('right',.8,.1,.15,.6)];
assert.equal(sectionAt('p',.25,.25,sections),'small');
assert.equal(sectionAt('p',.75,.4,sections),'right');
assert.equal(sectionAt('p',.99,.99,sections),null);
assert.equal(sectionAt('other',.25,.25,sections),null);
assert.equal(sectionAt('p',NaN,.3,sections),null);
assert.equal(sectionAt('p',null,.3,sections),null);
const q=(id,text,x=.4,page='p')=>enrichQuestion({id,text,x,y:.4,sessionId:'lecture',slideIndex:0,createdAt:`2026-01-01T00:00:0${id}Z`,status:'unanswered'},page,sections);
const input=[q('1','Pooling을 왜 사용하나요?'),q('2','Pooling이 필요한 이유는?'),q('3','Pooling이 무엇인가요?'),q('4','Max와 Average Pooling 차이는 무엇인가요?'),q('5','Pooling을 왜 사용하나요?',.85),q('6','Pooling을 왜 사용하나요?',.4,'another')];
const before=JSON.stringify(input);
const clusters=clusterSectionQuestions(input,()=>.96);
assert.equal(clusters.length,5);assert.equal(clusters[0].questionCount,2);
assert.equal(JSON.stringify(input),before);
assert.equal(classifyQuestionRule('Pooling layer의 목적이 뭔가요?'),'why');
assert.equal(classifyQuestionRule('Pooling 없이도 가능한가요?'),'deep_dive');
assert.equal(classifyQuestionRule('의료 영상에도 적용 가능한가요?'),'application');
assert.equal(classifyQuestionRule('시험 범위인가요?'),'logistics');
assert.equal(classifyQuestionRule('안녕하세요'),null);
const chain=[q('1','이유 A'),q('2','이유 B'),q('3','이유 C')];
assert.equal(clusterSectionQuestions(chain,(a,b)=>Math.abs(Number(a.original.id)-Number(b.original.id))===2?.7:.95).length,2);
assert.equal(clusterSectionQuestions([q('1','이유 A'),q('2','이유 B')],()=>undefined).length,2);
assert.equal(clusterSectionQuestions([q('1','같은 문구'),q('2','같은 문구')],()=>undefined).length,1);
assert.equal(clusterSectionQuestions([q('1','같은 문구',null),q('2','같은 문구',null)],()=>1).length,2);
const appended=clusterSectionQuestions([...input,q('7','Pooling의 목적은?')],()=>.96);
assert.equal(appended[0].id,clusters[0].id);
console.log('PASS: smallest/nearest/cutoff, invalid coordinates, page/section/intent isolation, no chaining, no mutation, stable IDs, offline fallback');
