export const translate = (locale: Locale, key: TranslationKey, values: Values = {}) => {
  const message = (locale === "ko" ? ko : en)[key];
  return typeof message === "function" ? message(values) : message;
};

export const categoryKeys: QuestionCategory[] = ["concept", "why", "example", "error", "important"];

export const categoryLabel = (locale: Locale, category: QuestionCategory) => {
  if ((categoryKeys as string[]).includes(category)) return translate(locale, `category.${category}` as TranslationKey);
  if ((LEGACY_QUESTION_CATEGORY_KEYS as readonly string[]).includes(category)) return translate(locale, `category.${category}` as TranslationKey);
  return category;
};

export const statusLabel = (locale: Locale, status: QuestionStatus) =>
  translate(locale, `status.${status}` as TranslationKey);

export const timeAgo = (locale: Locale, value: string) => {
  const seconds = Math.max(1, Math.floor((Date.now() - new Date(value).getTime()) / 1000));
  const formatter = new Intl.RelativeTimeFormat(locale === "ko" ? "ko-KR" : "en-US", { numeric: "always" });
  if (seconds < 60) return formatter.format(-seconds, "second");
  if (seconds < 3600) return formatter.format(-Math.floor(seconds / 60), "minute");
  if (seconds < 86400) return formatter.format(-Math.floor(seconds / 3600), "hour");
  return formatter.format(-Math.floor(seconds / 86400), "day");
};

