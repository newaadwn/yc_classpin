export const localizeUploadError = (locale: Locale, message: string) => {
  if (locale === "ko") return message;
  const match = uploadErrorKeys.find(([source]) => message.includes(source));
  return match ? translate(locale, match[1]) : /[가-힣]/.test(message) ? translate(locale, "upload.failed") : message;
};
